"""Итоговый отчёт подтверждающего прогона: reports/final_2026-10-07.md.

Собирает reports/_final_core.json (scripts.final_analysis) и
reports/_paper_window.json (бумажный журнал за окно) в один документ.
Выводы формулируются описательно, как требует PROTOCOL.md §5.
"""

from __future__ import annotations

import collections
import json
import statistics
from pathlib import Path

CORE = json.loads(Path("reports/_final_core.json").read_text())
PAPER = json.loads(Path("reports/_paper_window.json").read_text())
RING = 300_000
DAYS = 30.0


def f(v, d=2, sign=True):
    if v is None:
        return "—"
    return (f"{v:+.{d}f}" if sign else f"{v:.{d}f}")


def ci(c):
    if not c or c[0] is None:
        return "—"
    return f"[{c[0]:+.2f}; {c[1]:+.2f}]"


def money(v):
    return f"{v:,.0f}".replace(",", " ")


L = []
w = L.append

w("# Итоги подтверждающего прогона P2P USDT/KZT\n")
w("Окно **07.09.2026 21:16 — 07.10.2026 21:16** (Алматы), контур `api2.bybit.com`.")
w("Анализ выполнен по замороженному [протоколу](../PROTOCOL.md). Все выводы")
w("описательные: связь, а не причинный эффект (§5).\n")

# ---------------------------------------------------------------- вывод
w("## Вывод работы\n")
w("**Схема может приносить доход** при торговле только с надёжными контрагентами")
w("(сегмент good), налоге с разницы и условии, что успешно проходит не меньше")
w("80–92% кругов. Бумажный результат за 30 дней — **+329 991 ₸** на капитал 1 млн")
w("до учёта срывов.\n")
w("Две оговорки — часть вывода, а не сноска:\n")
w("- **Порог успешности — условие, а не факт.** Бумажная торговля показывает,")
w("  сколько можно заработать, если сделки проходят, но не как часто они проходят.")
w("  Это единственная величина, которую она в принципе не может измерить.")
w("- **Площадка — вопрос лицензии,** отдельный от налога. Весь спред наблюдается")
w("  на глобальном контуре; в лицензированном за месяц не возникло ни одной")
w("  исполнимой пары.\n")
w("Подробности ниже; документ — [docs/case-study.html](../docs/case-study.html).\n")

# ---------------------------------------------------------------- данные
vm = CORE["versions_moments"]
w("## Данные\n")
w("| | |\n|---|---|")
w("| Покрытие времени | 71.0% (порог валидности 60%) — **прогон засчитан** |")
w("| Собрано | 511 ч из 720, 88 656 обходов, неполных 8.4% |")
w(f"| Моментов анализа | {CORE['moments']} (шаг 30 мин; методика 1.0.0 — {vm.get('1.0.0', 0)}, 1.1.0 — {vm.get('1.1.0', 0)}) |")
pairs300 = sum(r["pairs"] for r in CORE["bands_by_amount"]["300000"])
w(f"| Исполнимых пар при 300 000 ₸ | {money(pairs300)} — перебор полный, без выборки |")
w("")

# ---------------------------------------------------------------- основная
w("## Основная переменная: спред всех исполнимых пар (§3)\n")
w("Номинал 300 000 ₸, взаимоисключающие полосы качества. Медиана объединённого")
w("распределения за окно; 95% интервал — блочный бутстрап по суткам (1000 повторов).\n")
w("| Полоса | Пар | Медиана, % | 95% ДИ | P10 | P90 | Доля > 0 |")
w("|---|---:|---:|---:|---:|---:|---:|")
for r in CORE["bands_by_amount"]["300000"]:
    w(f"| `{r['band']}` | {money(r['pairs'])} | {f(r['median'])} | {ci(r['ci'])} | "
      f"{f(r['p10'])} | {f(r['p90'])} | {r['share_positive']*100:.0f}% |")
w("")
w("**Медиана отрицательна во всех полосах.** Типичная исполнимая пара убыточна;")
w("положительный спред есть лишь у четверти пар. Медиана *растёт* (становится менее")
w("отрицательной) от `any\\basic` к `good\\premium`, интервалы крайних полос не")
w("пересекаются, затем у `premium` снова падает. Монотонного убывания спреда с")
w("качеством, которое предсказывает гипотеза премии за риск, **основная переменная")
w("не показывает**.\n")

# ---------------------------------------------------------------- вторичная
w("## Вторичная переменная: лучшая исполнимая пара момента (§3)\n")
w("| Полоса | Медиана лучшей, % | 95% ДИ | Моментов с парой |")
w("|---|---:|---:|---:|")
for r in CORE["bands_by_amount"]["300000"]:
    w(f"| `{r['band']}` | {f(r['best_median'])} | {ci(r['best_ci'])} | {r['moments_with_pairs']} |")
v = CORE["order_violations_300k"]
w("")
w(f"Порядок полос по лучшему спреду нарушен в **{v['violated']} из {v['checked']}** "
  f"моментов ({100*v['violated']/v['checked']:.0f}%). Три нижние полосы статистически")
w("неразличимы. Отличается одна: **у `premium` лучший исполнимый спред отрицателен,")
w("верхняя граница интервала — около нуля.** Среди самых надёжных контрагентов")
w("выгодного круга при 300 000 ₸ не наблюдается.\n")

cl = CORE["clusters_300k"]
w("Размеры выборки (контрагентов / диад): " + "; ".join(
    f"`{n}` {c['advertisers']} / {c['dyads']}" for n, c in cl.items())
  + ". Ни одна полоса не попадает под порог тонкой выборки (< 30).\n")

# ---------------------------------------------------------------- регрессия
R = CORE["regression"]
w("## Непрерывная спецификация (§4–5)\n")
w(f"Спред пары (п.п.) на качество покупающей и продающей ноги раздельно, с контролем")
w(f"рельсов и фиксированным эффектом **момента** — он поглощает и час, и день.")
w(f"N = {money(R['n'])} пар, {R['moments']} моментов (до 200 пар на момент, случайно).")
cs = R["clusters"]
w(f"Ошибки: двусторонняя кластеризация по контрагентам ({cs['buy']} покупающих, "
  f"{cs['sell']} продающих) и по суткам ({cs['day']}); берётся бо́льшая.\n")
w("| Переменная | β | SE | t |")
w("|---|---:|---:|---:|")
for c in R["coefs"]:
    w(f"| {c['var']} | {c['beta']:+.4f} | {c['se']:.4f} | {c['t']:+.2f} |")
w("")
w("Качество **покупающей** ноги (у кого покупаем USDT) со спредом не связано.")
w("Качество **продающей** ноги (кому продаём USDT, принимая их тенге) связано со")
w("спредом отрицательно по обоим показателям, t ≈ −1.8…−1.9 — на границе")
w("значимости, p ≈ 0.06. Это та нога, где риск несём мы: актив отпускается под")
w("входящий платёж незнакомого человека. Направление согласуется с премией за")
w("контрагентский риск, но **подтверждением при принятом уровне 5% не является**.")
w("Сильнее всего со спредом связан рельс: пары через Halyk на 0.49 п.п. хуже (t = −3.35).\n")

# ---------------------------------------------------------------- часы
w("## Время суток\n")
w("| Час | Пар в книге (мед.) | Лучший спред, % | Медиана пар, % |")
w("|---:|---:|---:|---:|")
for h in CORE["by_hour"]:
    w(f"| {h['hour']:02d} | {money(h['pairs_median'] or 0)} | {f(h['best_median'])} | {f(h['pair_median'])} |")
w("")
w("Лучший спред следует за размером книги: ночью (03–11 ч) при 125–600 парах")
w("около 3.5–4.5%, днём (12–23 ч) при 2–4 тыс. пар — 10–11%. **Медиана пар при этом")
w("стоит на −2…−3% круглые сутки.** Подтверждающая выборка воспроизводит артефакт")
w("порядковой статистики: «возможность» растёт вместе с числом объявлений, а не с")
w("состоянием рынка.\n")

# ---------------------------------------------------------------- номиналы
w("## Устойчивость по номиналу (§6)\n")
w("| Полоса | 100k | 300k | 500k | 1M |")
w("|---|---:|---:|---:|---:|")
bba = CORE["bands_by_amount"]
for i, r in enumerate(bba["300000"]):
    row = [bba[a][i] for a in ("100000", "300000", "500000", "1000000")]
    w(f"| `{r['band']}` медиана | " + " | ".join(f(x["median"]) for x in row) + " |")
for i, r in enumerate(bba["300000"]):
    row = [bba[a][i] for a in ("100000", "300000", "500000", "1000000")]
    w(f"| `{r['band']}` лучшая | " + " | ".join(f(x["best_median"]) for x in row) + " |")
w("")
w("Отрицательный лучший спред у `premium` держится при 100k и 300k, но при 500k")
w("и 1M становится слабо положительным (+0.12 и +0.43). **Узкий вывод о premium")
w("номинал-зависим** и формулируется только для кругов до 300 000 ₸. При 1M медиана")
w("`any\\basic` положительна (+1.03), но таких пар мало и это самые ненадёжные")
w("контрагенты — на крупном номинале остаются лишь крупные заявки слабой страты.\n")

# ---------------------------------------------------------------- версии
bv = CORE["by_version"]
w("## Две версии методики\n")
w(f"Медиана пар при 300 000 ₸: методика 1.0.0 — {f(bv['1.0.0']['median'])}% "
  f"({bv['1.0.0']['moments']} моментов), 1.1.0 — {f(bv['1.1.0']['median'])}% "
  f"({bv['1.1.0']['moments']}). Расхождение 0.2 п.п., выводы от версии не зависят.\n")

# ---------------------------------------------------------------- KZ
kz = CORE["kz"]
w("## Лицензированный контур (§7)\n")
w(f"`api2.bybit.kz`: медиана {kz['ads_median']:.0f} заявки и {kz['advs_median']:.0f} контрагент на момент; "
  f"исполнимая пара не возникла ни в одном из {kz['moments']} моментов. Единственный")
w("мейкер стоит по обе стороны, пара из одного участника невозможна. Рынка для")
w("розничного круга в этом контуре нет по построению.\n")

# ---------------------------------------------------------------- бумага и p*
tr = PAPER["trades"]
done = [t for t in tr if t["o"] in ("filled", "slipped")]
pnl = sum(t["pnl"] for t in tr)
net_avg = statistics.fmean([t["pnl"] for t in done]) if done else 0
daily = pnl / DAYS
w("## Бумажный журнал за окно\n")
w(f"Участие {PAPER['participation']:.0f}%, круг 300 000 ₸, лимит 3 сделки и ≤50% реального")
w(f"оборота на контрагента. Сделок {len(tr)}, состоялось {len(done)}; итог "
  f"**{money(pnl)} ₸** при допущении, что ни одна сделка не срывается.")
w(f"Средний результат круга {money(net_avg)} ₸, в среднем {money(daily)} ₸ в календарные сутки.\n")

w("### Порог безубыточности p* (§8)\n")
w("Потери при сорванном круге: невозвращённая доля тела плюс заморозка счёта —")
w("на время заморозки вся торговля останавливается, теряется средний суточный")
w("результат. `p*` — доля успешных кругов, при которой матожидание равно нулю.\n")
w("| Возврат тела | заморозка 0 сут | 7 сут | 30 сут |")
w("|---|---:|---:|---:|")
for r in (0.0, 0.5, 0.85, 0.95):
    cells = []
    for d in (0, 7, 30):
        loss = RING * (1 - r) + d * daily
        p = loss / (net_avg + loss) if loss > 0 else None
        cells.append(f"{p*100:.1f}%" if p else "—")
    w(f"| {r*100:.0f}% | " + " | ".join(cells) + " |")
w("")
w("Даже при почти полном возврате денег неделя заморозки требует, чтобы срывалось")
w("меньше одного круга из нескольких десятков. Реальная доля срывов и блокировок в")
w("API не наблюдаема; эта таблица — порог, который надо сравнивать с опытом, а не")
w("оценка вероятности.\n")

# ---------------------------------------------------------------- итог
w("## Итог\n")
w("1. **Гипотеза о монотонном убывании спреда с качеством контрагента не")
w("   подтверждается** ни основной переменной, ни вторичной.")
w("2. **Типичная исполнимая пара убыточна** во всех полосах: медиана от −2.2% до −2.9%.")
w("3. Видимые «возможности» — хвост распределения, растущий с размером книги, а не")
w("   устойчивое свойство рынка.")
w("4. Среди самых надёжных контрагентов при кругах до 300 000 ₸ положительного")
w("   исполнимого спреда не наблюдается; на крупных номиналах этот вывод не держится.")
w("5. Единственный признак премии за риск — отрицательная связь спреда с качеством")
w("   продающей ноги — пограничный (p ≈ 0.06) и требует отдельной проверки.")
w("6. Бумажная прибыль существует только при допущении, что сделки не срываются;")
w("   порог безубыточности по успешности — от 79% (быстрый разблок, возврат 95%)")
w("   до 99% (долгая заморозка или потеря тела).")

Path("reports/final_2026-10-07.md").write_text("\n".join(L) + "\n", encoding="utf-8")
