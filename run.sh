#!/bin/bash
# Запуск коллектора на macOS.
#
# caffeinate -i  не даёт машине уснуть в простое, пока процесс жив.
# Крышку всё равно лучше не закрывать — сон при закрытой крышке этим не
# отменяется, и в данных появится честно залогированная дыра.
cd "$(dirname "$0")"
exec caffeinate -i python3 -m collector.poller
